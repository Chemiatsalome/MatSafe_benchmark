"""
REPORT STATS -- the single source of truth for every number that appears in
CORPUS_LOG.md or the paper. Re-run this as the LAST step before any freeze
or paper draft. Every number in prose should trace to this script's output;
none should be hand-transcribed and left to drift when an upstream stage
changes (this is exactly how the 284-vs-296 validation-sample staleness
happened -- a count written by hand at time T, a lexicon fix at T+1).

Outputs:
  - stdout: human-readable report, safe to read off directly into prose
  - Maternal_RAG_Corpus/stats_report.json: machine-readable, for any
    downstream tooling (e.g. Stage 5+ manifests) that wants to cite the
    same numbers programmatically instead of re-deriving them.

Also records the current git commit hash, so any number in this report
(and anything built downstream of it, e.g. an embedding index's manifest)
can be traced back to an exact, inspectable corpus state.

Run:  python report_stats.py
"""
import csv
import json
import os
import subprocess
from collections import Counter

from pypdf import PdfReader

ROOT = "Maternal_RAG_Corpus"


def doc_stats():
    with open(os.path.join(ROOT, "metadata.csv"), encoding="utf-8") as f:
        docs = list(csv.DictReader(f))

    total_pages = 0
    total_chars = 0
    for d in docs:
        r = PdfReader(os.path.join(ROOT, "raw_pdfs", d["filename"]))
        total_pages += len(r.pages)
        ext_path = os.path.join(ROOT, "extracted_text", d["document_id"] + ".txt")
        total_chars += len(open(ext_path, encoding="utf-8").read())

    return {
        "total_documents": len(docs),
        "guideline_or_standard": sum(1 for d in docs if d["document_type"] in ("guideline", "standard")),
        "patient_education": sum(1 for d in docs if d["document_type"] == "patient_education"),
        "total_pages": total_pages,
        "total_extracted_characters": total_chars,
    }


def chunk_stats():
    out = {}
    for fname in sorted(os.listdir(os.path.join(ROOT, "chunks"))):
        with open(os.path.join(ROOT, "chunks", fname), encoding="utf-8") as f:
            out[fname[:-4]] = sum(1 for _ in csv.DictReader(f))
    return out


def tagging_stats():
    out = {}
    for fname in sorted(os.listdir(os.path.join(ROOT, "chunks_tagged"))):
        with open(os.path.join(ROOT, "chunks_tagged", fname), encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        out[fname[:-4]] = {
            "total_chunks": len(rows),
            "stance": dict(Counter(r["stance"] for r in rows)),
            "care_phase": dict(Counter(r["care_phase"] for r in rows)),
        }
    return out


def audit_stats():
    path = os.path.join(ROOT, "stance_audit.csv")
    if not os.path.exists(path):
        return {"total_mismatches": 0}
    with open(path, encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    para_500 = [r for r in rows if r["strategy"] == "para_500.csv"]
    return {
        "total_mismatches_all_strategies": len(rows),
        "para_500_mismatches": len(para_500),
        "para_500_mismatches_by_document": dict(Counter(r["document_id"] for r in para_500)),
    }


def validation_sample_stats():
    path = os.path.join(ROOT, "validation_sample.csv")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    return {"total": len(rows), "by_stance": dict(Counter(r["stance"] for r in rows))}


def query_stats():
    with open(os.path.join(ROOT, "query_set.csv"), encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return {
        "total_queries": len(rows),
        "by_topic_and_urgency": {
            f"{t}/{u}": c for (t, u), c in
            Counter((r["topic"], r["urgency_class"]) for r in rows).items()
        },
    }


def git_commit_hash():
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=os.path.dirname(os.path.abspath(__file__)),
            stderr=subprocess.DEVNULL,
        )
        return out.decode().strip()
    except Exception:
        return None


def main():
    report = {
        "generated_by": "report_stats.py",
        "corpus_git_commit": git_commit_hash(),
        "documents": doc_stats(),
        "chunks_per_strategy": chunk_stats(),
        "tagging": tagging_stats(),
        "stance_audit": audit_stats(),
        "validation_sample": validation_sample_stats(),
        "query_set": query_stats(),
    }

    out_path = os.path.join(ROOT, "stats_report.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    d = report["documents"]
    print("=" * 70)
    print("CANONICAL STATS REPORT -- generated by report_stats.py")
    print("=" * 70)
    print(f"Documents: {d['total_documents']} total "
          f"({d['guideline_or_standard']} guideline/standard + "
          f"{d['patient_education']} patient-education)")
    print(f"Pages: {d['total_pages']:,}")
    print(f"Extracted characters: {d['total_extracted_characters']:,}")
    print()
    print("Chunks per strategy:")
    for k, v in report["chunks_per_strategy"].items():
        print(f"  {k}: {v:,}")
    print()
    q = report["query_set"]
    print(f"Query set: {q['total_queries']} total")
    for k, v in sorted(q["by_topic_and_urgency"].items()):
        print(f"  {k}: {v}")
    print()
    print(f"Stance-audit mismatches (para_500): {report['stance_audit'].get('para_500_mismatches')}")
    print(f"Validation sample size: {report['validation_sample'].get('total')}")
    print()
    print(f"Corpus git commit: {report['corpus_git_commit']}")
    print(f"Full report: {out_path}")


if __name__ == "__main__":
    main()
